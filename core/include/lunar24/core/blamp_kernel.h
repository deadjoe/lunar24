// g(u): the windowed kernel at |u| in samples. Even; g(0) = 8/pi^2; exactly 0 for
// |u| >= L. NaN/0 map to the corner value (unchanged from before the extraction).
inline double blampKernel(double u) {
  const double a = std::fabs(u);
  if (!(a > 0.0)) return kBlampLut[0];          // u=0/NaN -> corner 8/pi^2.
  if (a >= 8) return 0.0;                       // windowed -> exactly 0 outside support.
  // The literal 8 below is the mandated L and is DELIBERATELY spelled out: it is what
  // tools/gen_gh19_blamp.py --check-prod derives L from, and that derivation must stay
  // an independent cross-check (against the KNOWN mandate) rather than read back a
  // symbol it is supposed to be validating. The static_assert keeps the literal and
  // the named constant from drifting apart.
  static_assert(kBlampSupport == 8.0, "check-prod derives L from the literal 8");
  const double tk = a / 8 * kN_blamp;
  const int i = static_cast<int>(tk);
  const double fr = tk - (double)i;
  return kBlampLut[i] * (1.0 - fr) + kBlampLut[i + 1] * fr;
}

// True when the support radius has reached half a period, i.e. when the peak and
// valley corners merge and the phase-local corner model is no longer verifiable.
// `stepCycles` is the caller's per-sample phase increment in cycles. Both callers
// reach the SAME physical predicate because each passes its own increment:
//   VCO triangle : step = dt      -> 8*dt >= 0.5
//   Schmitt ramp : step = 0.5*r   -> 8*(r/2) = 4r >= 0.5  <=> M = 1/r <= 8
// On this branch the caller must return the bounded naive waveform (NO correction)
// and list the range honestly (not as improved coverage).
inline bool blampSupportReachesHalfPeriod(double stepCycles) {
  return stepCycles * kBlampSupport >= 0.5;
}


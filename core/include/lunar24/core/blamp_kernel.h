// task #109 (GH#19 S1): the SHARED windowed analytic BLAMP kernel.
//
// Several product oscillators have a SLOPE (first-derivative) discontinuity rather
// than a value jump, so the correct band-limiting tool for all of them is the same
// BLAMP kernel. This header is its single source of truth: it carries no oscillator
// state and is a pure function of (distance in samples, magnitude), so extracting it
// changes no caller's arithmetic -- it removes a second copy, it does not change a
// result. Both users are frozen to the SAME L=8 window:
//
//   * Vco::triangleBlampCorr   (VCO triangle: slope reversal at the peak/valley)
//   * SchmittOsc::railBlampCorr (Schmitt ramp: slope reversal at the rail clamp)
//
// Windowed analytic BLAMP residual (Esqueda, Valimaki & Bilbao, "Rounding Corners
// with BLAMP", Proc. DAFx-16, Brno, 2016).
//
// The triangle has first-derivative (slope) discontinuities at the peak (phase =
// integer, slope jumps -8) and valley (phase = half-integer, slope jumps +8).
// A BLAMP is the correct band-limiting kernel for a slope jump (it is the
// antiderivative of a BLEP). The ideal 2nd-integral kernel h(2) minus its trivial
// ramp gives the dimensionless residual R(u) (paper Eq.(6) form, U-sized), which
// is EVEN about the corner (R(-u)=R(u)) with R(0)=1/pi^2. We window it with an
// explicit C1 Hann window w(u)=cos^2(pi*u/(2L)) of support L=8 samples, so the
// CONTINUOUS kernel has both value AND first derivative -> 0 at the support edge.
// The scaled kernel g(u) = 8*R(u)*w(u) has corner 8/pi^2 (~0.810569469); per the
// paper (S4.1) it is scaled by 2*mu with mu = 4*|step|, so 2*mu = 8*|step|, encoded
// by calling the kernel with the per-sample distance and multiplying by mag = |step|.
//
// The kernel is evaluated by a LINEAR-INTERPOLATION look-up table (N=256 points over
// [0,L]), generated by tools/gen_gh19_blamp.py --L 8 --N 256. Consequently the FINAL
// discrete kernel is piecewise-linear (C0), only approximating the C1 continuous
// kernel; the residual at/beyond the support edge is exactly 0, but the LAST
// interpolation segment carries a small residual slope (~-6.9e-6) before dropping
// to 0 outside support -- a tiny, quantified discontinuity in slope (not a value
// jump). Pure function of (phase, step), no cross-block state, causal, no added
// latency. It is a truncated approximation, NOT the exact infinite-support kernel,
// and is labeled accordingly (no "no-droop"/"exact" claim).
//
// NOT a license to invent scale factors: each caller must derive its own mag from
// its OWN slope jump (the kernel carries the 8, not the caller's amplitude law).

